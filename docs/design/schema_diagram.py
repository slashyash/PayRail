#!/usr/bin/env python3
"""Generate the relational schema diagram (schema.dot) from the LIVE database catalog.

Usage (admin libpq env set, e.g. inside the compose container or with PGHOST/PGUSER/...):
    python3 docs/design/schema_diagram.py payrail > docs/design/schema.dot
    neato -n -Tsvg docs/design/schema.dot -o docs/design/schema.svg   # build.sh does this

Every table, column, type, PK / FK / single-column UNIQUE flag and every foreign key edge is
read from pg_catalog, so the figure always matches the implemented schema (db/schema/02_tables.sql).
"""
import csv, io, subprocess, sys

DB = sys.argv[1] if len(sys.argv) > 1 else "payrail"

def q(sql):
    out = subprocess.run(["psql", "-X", "-q", "-A", "-F", "\t", "-t", "-d", DB, "-c", sql],
                         check=True, capture_output=True, text=True).stdout
    return [r for r in csv.reader(io.StringIO(out), delimiter="\t") if r]

cols = q("""
SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), (NOT a.attnotnull)::int, a.attnum
  FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = 'payrail' AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped
 ORDER BY c.relname, a.attnum""")
cons = q("""
SELECT c.relname, k.contype, k.conname, array_to_string(ARRAY(
         SELECT a.attname FROM unnest(k.conkey) WITH ORDINALITY u(n, o)
           JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = u.n ORDER BY u.o), ','),
       coalesce(f.relname, ''), array_to_string(ARRAY(
         SELECT a.attname FROM unnest(k.confkey) WITH ORDINALITY u(n, o)
           JOIN pg_attribute a ON a.attrelid = k.confrelid AND a.attnum = u.n ORDER BY u.o), ',')
  FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
  LEFT JOIN pg_class f ON f.oid = k.confrelid
 WHERE n.nspname = 'payrail' AND k.contype IN ('p', 'f', 'u')
 ORDER BY c.relname, k.conname""")

tables = {}
for t, col, typ, nullable, _ in cols:
    tables.setdefault(t, []).append({"name": col, "type": typ.replace("timestamp with time zone", "timestamptz")
                                     .replace("character(1)", "char(1)"), "null": nullable == "1",
                                     "pk": False, "fk": False, "uq": False})
fks = []
for t, kind, name, keycols, ftable, fcols in cons:
    keys = keycols.split(",")
    for c in tables[t]:
        if c["name"] in keys:
            if kind == "p": c["pk"] = True
            if kind == "f": c["fk"] = True
            if kind == "u" and len(keys) == 1: c["uq"] = True
    if kind == "f":
        fks.append((t, keys[0], ftable, fcols.split(",")[0]))

# placement: a 4 x 3 grid (rendered with `neato -n`, positions pinned) so the figure is compact
# enough to stay readable on an A4 page. Rows top to bottom, columns left to right.
GRID = [["ledger_lines", "journal_entries", "payments", "orders"],
        ["accounts", "gateway_settlements", "refunds", "order_items"],
        ["payouts", "vendors", "products", "users"]]
GAP_X, GAP_Y = 46, 30
ROW_PT, HEAD_PT, CHAR_PT = 18.2, 20.0, 5.6       # approximate box metrics at fontsize 10.5

def size(t):
    w = max(len(t) * CHAR_PT * 1.1, max(len(c["name"]) + len(c["type"]) + 4 + 3 * (c["pk"] + c["fk"] + c["uq"])
                                       + (5 if c["null"] else 0) for c in tables[t]) * CHAR_PT)
    return w + 10, HEAD_PT + ROW_PT * len(tables[t])

def label(t):
    rows = [f'<TR><TD BGCOLOR="#dbe5f3" COLSPAN="1"><B>{t}</B></TD></TR>']
    for c in tables[t]:
        flags = " ".join(f for f, on in (("PK", c["pk"]), ("FK", c["fk"]), ("UQ", c["uq"])) if on)
        name = f'<U>{c["name"]}</U>' if c["pk"] else c["name"]
        extra = f' <FONT COLOR="#8a94a3">{c["type"]}{" null" if c["null"] else ""}</FONT>'
        rows.append(f'<TR><TD PORT="{c["name"]}" ALIGN="LEFT">{name}'
                    f'{" <B>" + flags + "</B>" if flags else ""}{extra}</TD></TR>')
    return ('<<TABLE BORDER="1" CELLBORDER="1" CELLSPACING="0" CELLPADDING="2" COLOR="#2f4f7f">'
            + "".join(rows) + "</TABLE>>")

out = ["// generated by docs/design/schema_diagram.py from the payrail catalog — do not edit by hand",
       "// render: neato -n -Tsvg schema.dot -o schema.svg  (node positions are pinned)",
       "digraph schema {",
       '  graph [splines=true, fontname="Inter", pad=0.04, outputorder=edgesfirst];',
       '  node  [shape=plaintext, fontname="Inter", fontsize=10.5, margin=0];',
       '  edge  [color="#55657a", arrowsize=0.6, penwidth=0.9];']
col_w = [max(size(GRID[r][c])[0] for r in range(len(GRID))) for c in range(len(GRID[0]))]
row_h = [max(size(t)[1] for t in row) for row in GRID]
pos, x0 = {}, 0
xs = []
for w in col_w:
    xs.append(x0); x0 += w + GAP_X
y_top = sum(row_h) + GAP_Y * (len(GRID) - 1)
for r, row in enumerate(GRID):
    for c, t in enumerate(row):
        w, h = size(t)
        pos[t] = (xs[c] + col_w[c] / 2, y_top - h / 2)
    y_top -= row_h[r] + GAP_Y
for t in sorted(tables):
    x, y = pos[t]
    out.append(f'  {t} [pos="{x:.0f},{y:.0f}!", label={label(t)}];')
# compass points for edges that would otherwise cut through a table in this grid
PORTS = {("orders", "customer_id"): (":e", ":e")}
for t, c, ft, fc in fks:
    tp, hp = PORTS.get((t, c), ("", ""))
    out.append(f"  {t}:{c}{tp} -> {ft}:{fc}{hp};")
out.append("}")
print("\n".join(out))
assert len(tables) == 12 and len(fks) == 16, (len(tables), len(fks))
